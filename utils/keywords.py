def fuzzy_match_osm_tag(keyword: str) -> Optional[Tuple[str, str]]:
    """Fuzzy match a keyword to an OSM tag."""
    keyword_lower = keyword.lower().strip()

    # Exact match first
    if keyword_lower in ALL_OSM_VALUES:
        return ALL_OSM_VALUES[keyword_lower]

    # Fuzzy match
    all_values = list(ALL_OSM_VALUES.keys())
    matches = difflib.get_close_matches(keyword_lower, all_values, n=1, cutoff=0.6)

    if matches:
        return ALL_OSM_VALUES[matches[0]]

    return None


def get_osm_tags(query: str) -> List[Tuple[str, str]]:
    """
    Get ALL OSM tag pairs for ANY user keyword.

    Returns: [(tag_key, tag_value), ...]
    Example: "pharmacy" -> [("amenity", "pharmacy"), ("shop", "chemist")]
    Example: "boulangerie" -> [("shop", "bakery")]
    Example: "teppanyaki" -> [] (empty, use name search fallback)
    """
    query_lower = query.lower().strip()

    # Layer 1: Exact match in BUSINESS_TYPES
    if query_lower in BUSINESS_TYPES:
        tags = []
        bt = BUSINESS_TYPES[query_lower]
        for key in ["osm_amenity", "osm_shop", "osm_tourism", "osm_healthcare",
                     "osm_leisure", "osm_craft", "osm_office"]:
            if key in bt:
                tag_key = key.replace("osm_", "")
                tags.append((tag_key, bt[key]))
        return tags

    # Layer 2: Reverse lookup (non-English to English)
    if query_lower in REVERSE_MAP:
        eng_type = REVERSE_MAP[query_lower]
        return get_osm_tags(eng_type)

    # Layer 3: Fuzzy match against OSM tag values
    match = fuzzy_match_osm_tag(query_lower)
    if match:
        return [match]

    # Layer 4: No tag match - will use name search
    return []


def get_osm_tags_for_bbox(query: str, bbox: Tuple) -> str:
    """Build Overpass QL filter string for all tag types in a bbox."""
    tags = get_osm_tags(query)
    filter_lines = []

    for tag_key, tag_value in tags:
        filter_lines.append(f'nwr["{tag_key}"="{tag_value}"]({bbox[0]},{bbox[1]},{bbox[2]},{bbox[3]});')

    # Always add name search as fallback
    escaped_query = query.replace('"', '\\"')
    filter_lines.append(f'nwr["name"~"{escaped_query}",i]({bbox[0]},{bbox[1]},{bbox[2]},{bbox[3]});')

    return "\n".join(filter_lines)

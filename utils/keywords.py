def detect_country(location: str) -> str:
    """Detect country from location string."""
    loc_lower = location.lower().strip()

    for key, langs in COUNTRY_LANGUAGES.items():
        if key in loc_lower or loc_lower in key:
            return key

    return ""


def get_languages_for_country(country: str) -> List[str]:
    """Get language priority list for a country."""
    country_lower = country.lower().strip()
    return COUNTRY_LANGUAGES.get(country_lower, ["en"])


def get_accept_language(country: str) -> str:
    """Get Accept-Language header for a country."""
    languages = get_languages_for_country(country)
    if languages:
        return ACCEPT_LANGUAGE_HEADERS.get(languages[0], "en-US,en;q=0.9")
    return "en-US,en;q=0.9"


def get_contact_paths_for_country(country: str) -> List[str]:
    """Get contact paths to crawl based on country."""
    languages = get_languages_for_country(country)
    paths = []

    for lang in languages:
        lang_paths = CONTACT_PATHS_BY_LANG.get(lang, [])
        paths.extend(lang_paths)

    # Always include English paths as fallback
    for path in CONTACT_PATHS_BY_LANG["en"]:
        if path not in paths:
            paths.append(path)

    return paths


def expand_query(query: str, country: str) -> List[str]:
    """
    Expand a query to all relevant languages for a country.

    User types "pharmacy" → returns ["pharmacy", "pharmacie", "صيدلية", "薬局"]
    User types "صيدلية" → detects it's Arabic → returns ["pharmacy", "pharmacie", "薬局"]
    """
    query_lower = query.lower().strip()

    # Step 1: Try direct match (user typed English)
    if query_lower in BUSINESS_TYPES:
        entry = BUSINESS_TYPES[query_lower]
        languages = get_languages_for_country(country)
        expanded = []
        for lang in languages:
            if lang in entry:
                expanded.extend(entry[lang])
        if "en" in entry:
            for w in entry["en"]:
                if w not in expanded:
                    expanded.append(w)
        return list(dict.fromkeys(expanded))

    # Step 2: Try reverse lookup (user typed in any language)
    if query_lower in REVERSE_MAP:
        eng_type = REVERSE_MAP[query_lower]
        return expand_query(eng_type, country)

    # Step 3: Try partial match
    for key, eng_type in REVERSE_MAP.items():
        if query_lower in key or key in query_lower:
            return expand_query(eng_type, country)

    # Step 4: Return as-is (unknown term)
    return [query]


def get_osm_amenity(query: str) -> str:
    """Get the OSM amenity type for a query."""
    query_lower = query.lower().strip()

    if query_lower in BUSINESS_TYPES:
        entry = BUSINESS_TYPES[query_lower]
        return entry.get("osm_amenity") or entry.get("osm_shop") or entry.get("osm_tourism") or query_lower

    if query_lower in REVERSE_MAP:
        eng_type = REVERSE_MAP[query_lower]
        if eng_type in BUSINESS_TYPES:
            entry = BUSINESS_TYPES[eng_type]
            return entry.get("osm_amenity") or entry.get("osm_shop") or entry.get("osm_tourism") or query_lower

    return query_lower


def get_all_languages_for_query(query: str) -> List[str]:
    """Get ALL language translations for a query (for maximum coverage)."""
    query_lower = query.lower().strip()

    if query_lower in BUSINESS_TYPES:
        all_words = []
        for lang_words in BUSINESS_TYPES[query_lower].values():
            if isinstance(lang_words, list):
                all_words.extend(lang_words)
        return list(dict.fromkeys(all_words))

    if query_lower in REVERSE_MAP:
        eng_type = REVERSE_MAP[query_lower]
        return get_all_languages_for_query(eng_type)

    return [query]


